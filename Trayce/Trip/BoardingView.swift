import ActivityKit
import SwiftUI
import TrayceCore

struct BoardingView: View {
    @Environment(TripStore.self) private var store
    @Environment(BagCheckModel.self) private var bag
    let trip: Trip
    @State private var activityMessage: String?

    private var b: Booking { trip.current.booking }
    private var pass: BoardingPassData? { trip.current.barcodePayload.flatMap(BCBPParser.parse) }

    var body: some View {
        ScrollView {
            VStack(spacing: 18) {
                VStack(alignment: .leading, spacing: 16) {
                    Text("\(b.origin) → \(b.destination) · \(b.departure.formatted(.dateTime.weekday().day().month()))")
                        .font(.subheadline).foregroundStyle(.secondary)
                    Text("Boarding \(b.departure.addingTimeInterval(-35 * 60).formatted(date: .omitted, time: .shortened))")
                        .font(.title.bold())
                    if let image = store.barcodeImage(for: trip.current) {
                        Image(uiImage: image).resizable().interpolation(.none).scaledToFit()
                            .frame(maxWidth: .infinity).padding(8).background(.white)
                            .accessibilityLabel("Boarding barcode from the airline document")
                        Text("Cropped from \(trip.current.fileName), not generated by Trayce")
                            .font(.caption).foregroundStyle(.secondary)
                    } else {
                        Label("No barcode found in the current document. Show the airline's own boarding pass.", systemImage: "barcode.viewfinder")
                            .font(.subheadline).foregroundStyle(.secondary)
                    }
                    Grid(alignment: .leading, horizontalSpacing: 28) {
                        GridRow { Text("Gate"); Text("Seat"); Text("Seq") }.font(.caption).foregroundStyle(.secondary)
                        GridRow { Text(b.gate ?? "—"); Text(pass?.seat ?? b.seat ?? "—"); Text(pass?.sequence ?? "—") }.font(.title2.bold())
                    }
                }
                .padding(20)
                .foregroundStyle(.black)
                .background(.white, in: .rect(cornerRadius: 24))

                Label("Gate comes from your document, not live data. Check the airport screens.", systemImage: "exclamationmark.circle")
                    .font(.footnote).foregroundStyle(.orange)

                Button("Pin to Lock Screen", systemImage: "lock.rectangle.stack") { startActivity() }
                    .buttonStyle(.borderedProminent)
                if let activityMessage { Text(activityMessage).font(.footnote).foregroundStyle(.secondary) }
            }
            .padding()
        }
        .background(Color.black)
        .navigationTitle("Boarding")
        .toolbarColorScheme(.dark, for: .navigationBar)
    }

    private func startActivity() {
        guard ActivityAuthorizationInfo().areActivitiesEnabled else {
            activityMessage = "Live Activities are turned off for Trayce in Settings."
            return
        }
        let attributes = TrayceActivityAttributes(flight: b.flightLabel, gate: b.gate ?? "—")
        let state = TrayceActivityAttributes.ContentState(step: "Security", trays: bag.trayLines,
                                                          boardsAt: b.departure.addingTimeInterval(-35 * 60))
        do {
            _ = try Activity.request(attributes: attributes,
                                     content: ActivityContent(state: state, staleDate: b.departure))
            activityMessage = "Pinned. It goes stale at departure time."
        } catch {
            activityMessage = "Couldn't start the Live Activity: \(error.localizedDescription)"
        }
    }
}
